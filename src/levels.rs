pub struct PlatformSpec {
    pub x: usize,
    pub y: usize,
    pub width: usize,
    pub travel: (i32, i32),
    pub crumble: bool,
}
const fn slide(x: usize, y: usize, width: usize, dx: i32, dy: i32) -> PlatformSpec {
    PlatformSpec {
        x,
        y,
        width,
        travel: (dx, dy),
        crumble: false,
    }
}
const fn crumble(x: usize, y: usize, width: usize) -> PlatformSpec {
    PlatformSpec {
        x,
        y,
        width,
        travel: (0, 0),
        crumble: true,
    }
}

